// Alpine.data() registrations.
//
// This file MUST load before the Alpine CDN tag in head.handlebars.
// Alpine's CDN build calls Alpine.start() inside a queueMicrotask that
// fires immediately after its own script tag — before the next deferred
// script — so an alpine:init listener registered later never runs.
//
// Unlike the character-* modules this is loaded from <head>, outside the
// hx-boost swap region, so it executes exactly once and can use const.

// Matches the slug rule the page editor's deleted inline script used,
// character-for-character: lowercase, trim, strip anything that is not a
// word character/space/dash, collapse whitespace runs to a dash, collapse
// dash runs to a dash, trim leading/trailing dashes. Word characters
// include underscore, and nothing here targets underscores separately, so
// underscores pass through untouched (e.g. "foo_bar" stays "foo_bar") --
// that is intentional, not an oversight; a version that folds underscores
// into dashes changes real slugs and silently flips the on-load "was this
// auto-generated" derivation below for any existing page whose title has
// an underscore.
//
// The `(value || '')` guard is new: the inline script always read from
// title.value (always a string), but this helper's callers include the
// pageSlug() seed values below, which come from {{json page.title}} and
// can be `null` for a brand-new page.
const slugify = (value) => (value || '')
  .toLowerCase()
  .trim()
  .replace(/[^\w\s-]/g, '')
  .replace(/\s+/g, '-')
  .replace(/-+/g, '-')
  .replace(/^-+|-+$/g, '');

// The one rule every stat block control obeys: clicking the block at
// 1-based position `slot` sets the stat to `slot`, EXCEPT that clicking the
// block you are already on steps DOWN by one -- that is how a stat reaches
// zero, and it matches what the wizard's grid already did when you clicked
// a point you had assigned.
//
// `floor` is the number of points the click may not take the stat below
// (class + personality points in the wizard; 0 everywhere else). `ceiling`
// is the highest total the click may produce (the per-stat cap, or the
// remaining point budget, whichever binds first).
//
// Exported on `window` rather than closed over because
// public/js/character-wizard.js renders its own imperative grid and has to
// apply the identical rule. Two copies of this arithmetic is exactly how
// the wizard and the editor would drift apart. alpine-components.js is a
// deferred <head> script and character-wizard.js a deferred body script, so
// deferred-script document order guarantees this is defined first.
const resolveStatTarget = ({ slot, current, floor = 0, ceiling }) => {
  const target = slot === current ? slot - 1 : slot;
  return Math.max(floor, Math.min(target, ceiling));
};

window.StatBlocks = { resolveStatTarget };

document.addEventListener('alpine:init', () => {
  // Title -> slug sync for the page editor. Stops as soon as the slug is
  // edited by hand. On load, a slug that still matches its title is
  // treated as auto-generated so it keeps following; one that differs is
  // treated as hand-written and left alone. Replaces a 43-line inline
  // script that tracked the same "was this auto-generated" flag in a
  // data-autoGenerated attribute.
  //
  // onTitle() re-arms auto-fill whenever the slug is empty, not just
  // while `auto` is already true -- the deleted script's condition was
  // `!slugInput.value || slugInput.dataset.autoGenerated === 'true'`.
  // Clearing a hand-edited slug back to '' and resuming typing in the
  // title must start it following again (the help text right below the
  // slug field promises exactly this: "Leave empty to auto-generate from
  // title"). Setting `auto = true` here matters as much as the fill
  // itself: without it, the very next keystroke sees `auto` still false
  // and `slug` no longer empty (just filled), so it would stop following
  // after a single refill instead of continuing to track the title.
  Alpine.data('pageSlug', (initialTitle, initialSlug) => ({
    title: initialTitle || '',
    slug: initialSlug || '',
    auto: !initialSlug || initialSlug === slugify(initialTitle),

    onTitle() {
      if (this.auto || !this.slug) {
        this.slug = slugify(this.title);
        this.auto = true;
      }
    }
  }));
  // Inline stats editor on the character show page. Replaces the old
  // vanilla-JS stats-editor module (now deleted).
  //
  // The save stays a fetch rather than becoming hx-patch: the endpoint
  // responds with JSON, so htmx would try to swap a JSON body into the
  // DOM. Changing the route is out of scope.
  Alpine.data('characterStats', (characterId, initialStats) => ({
    editing: false,
    saving: false,
    error: '',
    stats: Object.assign({}, initialStats),
    root: null,

    init() {
      // Capture the x-data root here, not inside edit(). $el is bound to
      // whichever element invoked the current method — inside edit() that
      // is the Edit <button> itself (called via @click="edit()"), which has
      // no .stats-input descendants, so querySelector off $el there always
      // returns null and focus silently never moves. init() runs with $el
      // bound to the x-data root, which does contain the inputs.
      this.root = this.$el;
    },

    get total() {
      return Object.values(this.stats)
        .reduce((sum, value) => sum + (parseInt(value, 10) || 0), 0);
    },

    edit() {
      this.error = '';
      this.editing = true;
      this.$nextTick(() => {
        const first = this.root.querySelector('.stats-input');
        if (first) first.focus();
      });
    },

    cancel() {
      this.error = '';
      this.editing = false;
      this.stats = Object.assign({}, initialStats);
    },

    save() {
      this.error = '';
      this.saving = true;

      // Coerce to integers and clamp to [0, 20], matching the range the
      // old module enforced before PATCHing.
      const payload = {};
      Object.keys(this.stats).forEach((stat) => {
        let n = parseInt(this.stats[stat], 10);
        if (isNaN(n) || n < 0) n = 0;
        if (n > 20) n = 20;
        payload[stat] = n;
      });

      return fetch('/characters/' + encodeURIComponent(characterId) + '/stats', {
        method: 'PATCH',
        headers: Object.assign(CharacterCommon.getAuthHeader(), {
          'Accept': 'application/json',
          'Content-Type': 'application/json'
        }),
        body: JSON.stringify(payload)
      }).then((res) => {
        if (!res.ok) {
          return res.text().then((text) => {
            throw new Error(text || ('HTTP ' + res.status));
          });
        }
        window.location.reload();
      }).catch((err) => {
        this.error = 'Save failed: ' + ((err && err.message) || 'Unknown error');
      }).finally(() => {
        this.saving = false;
      });
    }
  }));

  // Star-rating stat selector. Backs every stat-editing surface: the inline
  // stats editor, the level-up modal, the character form, and the class
  // form. Replaces the number inputs all four used to render.
  //
  // `value` is the committed points, `preview` the block the pointer is
  // currently over (or null). `previewValue` deliberately runs the hovered
  // block through the same resolveStatTarget the click uses, so the preview
  // shows what will HAPPEN, not merely what is under the cursor -- hovering
  // the block you are already on previews one lower, because that is what
  // clicking it does.
  //
  // Keyboard commits immediately rather than previewing: arrowing IS the
  // preview, and a focus-driven preview would fight the click preview for
  // the same `preview` slot every time focusBlock() moved focus after a
  // click.
  Alpine.data('statBlocks', (initial, max, stat) => ({
    value: parseInt(initial, 10) || 0,
    preview: null,
    max: max,
    stat: stat,

    // A stat already above `max` (the editor historically allowed 0-20) can
    // step DOWN through the blocks but must never be raised by them, so the
    // ceiling floats up to the current value and ratchets back down as the
    // value falls.
    get ceiling() {
      return Math.max(this.max, this.value);
    },

    get previewValue() {
      if (this.preview === null) return null;
      return resolveStatTarget({
        slot: this.preview, current: this.value, floor: 0, ceiling: this.ceiling
      });
    },

    boxClass(i) {
      const shown = this.previewValue;
      if (shown !== null) return i <= shown ? 'is-preview' : 'is-empty';
      return i <= this.value ? 'is-set' : 'is-empty';
    },

    tabIndex(i) {
      // Roving tabindex: the grid costs one tab stop per stat, exactly what
      // the 12 number inputs it replaces cost.
      return i === Math.max(1, Math.min(this.value, this.max)) ? 0 : -1;
    },

    set(i) {
      this.commit(resolveStatTarget({
        slot: i, current: this.value, floor: 0, ceiling: this.ceiling
      }));
      this.focusBlock(this.value);
    },

    commit(next) {
      const clamped = Math.max(0, Math.min(next, this.ceiling));
      this.preview = null;
      if (clamped === this.value) return;
      this.value = clamped;
      // Surfaces without Alpine state (the level-up modal) read the hidden
      // input, which fires no native `input` event when set programmatically.
      this.$dispatch('stat-change', { stat: this.stat, value: this.value });
    },

    focusBlock(n) {
      const idx = Math.max(1, Math.min(n, this.max));
      this.$nextTick(() => {
        const el = this.$root.querySelectorAll('[role="radio"]')[idx - 1];
        if (el) el.focus();
      });
    },

    key(e) {
      if (e.key === ' ' || e.key === 'Enter') {
        const all = Array.prototype.slice.call(this.$root.querySelectorAll('[role="radio"]'));
        const idx = all.indexOf(e.target);
        if (idx === -1) return;
        e.preventDefault();
        this.set(idx + 1);
        return;
      }
      let next;
      if (e.key === 'ArrowLeft' || e.key === 'ArrowDown') next = this.value - 1;
      else if (e.key === 'ArrowRight' || e.key === 'ArrowUp') next = this.value + 1;
      else if (e.key === 'Home') next = 0;
      else if (e.key === 'End') next = this.max;
      else return;
      // Otherwise arrows scroll the page out from under the control.
      e.preventDefault();
      this.commit(next);
      this.focusBlock(this.value);
    }
  }));

  // Bulma modal shell. Replaces App.openModal / App.closeModal.
  //
  // Listens on the window so code outside Alpine can drive it:
  //   window.dispatchEvent(new CustomEvent('open-modal', { detail: 'levelUp' }))
  // That is how public/js/character-level-up.js opens its modal without
  // being rewritten.
  //
  // Factored out (not registered directly) so `clearingModal` below can
  // build on the exact same open/close guards instead of reimplementing
  // them -- the name-scoping check and the "already closed, don't double
  // -unlock the body" guard would otherwise have to be kept in sync by hand
  // in two places.
  //
  // `body.modal-open` is a DOCUMENT-level class owned by a COMPONENT-level
  // lifetime, and a page can hold several modals at once (class-view ships
  // two, my-classes renders one per row). A bare add/remove pair gets both
  // ends of that wrong: an hx-boost swap tears an open modal out of the DOM
  // without ever calling close(), so the class outlives the modal and rides
  // along to a page that has none -- while a teardown that dropped the class
  // unconditionally would unlock the body out from under a sibling modal that
  // is still open. So the class is DERIVED from one shared count of modals
  // that are currently open, and every transition (open, close, teardown)
  // goes through that count.
  //
  // This is about not leaking stale state, not about restoring a scroll lock:
  // `body.modal-open { overflow: hidden }` never reaches the viewport, because
  // Bulma's minireset leaves <html> computing to `overflow: hidden scroll` and
  // overflow only falls through to <body> when <html>'s own is `visible`. The
  // lock has never worked in this app; fixing that is a separate decision.
  let openModals = 0;

  const syncBodyLock = () => {
    document.body.classList.toggle('modal-open', openModals > 0);
  };

  const modalBase = (name) => ({
    show: false,

    open(which) {
      if (which !== name) return;
      // Already open: re-opening must not count a second time, or the body
      // would stay locked after the one close() that follows.
      if (this.show) return;
      this.show = true;
      openModals += 1;
      syncBodyLock();
    },

    // which mirrors open()'s parameter but stays optional: every in-modal
    // @click="close()" call omits it and means "close me". The window
    // listener passes $event.detail explicitly so a close-modal broadcast
    // for a DIFFERENT modal's name doesn't close (or clear the body lock
    // for) this one.
    close(which) {
      if (which !== undefined && which !== name) return;
      if (!this.show) return;
      this.show = false;
      openModals -= 1;
      syncBodyLock();
    },

    // Alpine calls destroy() when the component's element leaves the DOM --
    // which is exactly what an hx-boost swap does to every modal on the page.
    // Delegating to close() (rather than stripping the class outright) gives
    // back only THIS modal's share of the count, so a sibling modal that is
    // still open keeps the body locked, and the guards above make a teardown
    // of an already-closed modal a no-op.
    destroy() {
      this.close();
    }
  });

  Alpine.data('modal', modalBase);

  // A modal that also blanks a result target when it actually closes --
  // e.g. the class-view unlock-code modal, which must not show a
  // previously-generated code on reopen. Replaces the
  // data-clear-on-close/data-clear-target attribute contract that only
  // App.closeModal used to honour.
  //
  // Built on modalBase so name-scoping and the double-close guard aren't
  // reimplemented here. closeAndClear() captures `wasOpen` before
  // delegating to close(which) so the clear only fires when THIS call
  // actually transitioned the modal from open to closed:
  //   - a real close (background/delete/footer/Escape) -> clears
  //   - Escape while a DIFFERENT modal is open (this one already closed)
  //     -> wasOpen is false -> no spurious clear
  //   - a close-modal broadcast for a different name while this one is
  //     open -> close(which) returns early on the name mismatch, show
  //     stays true -> skips the clear along with the close
  Alpine.data('clearingModal', (name) => ({
    ...modalBase(name),

    closeAndClear(which) {
      const wasOpen = this.show;
      this.close(which);
      if (wasOpen && !this.show && this.$refs.result) this.$refs.result.innerHTML = '';
    }
  }));

  // Click-to-sort table. Replaces the inline script in
  // views/character-list.handlebars.
  Alpine.data('sortableTable', () => ({
    key: null,
    dir: 1,

    // `$el` inside a method binds to the element that INVOKED it — here the
    // clicked <th>, not the table. Querying 'thead th' from a <th> returns
    // nothing, colIndex resolves to -1, and sorting silently does nothing.
    // Capture the root in init(), where `$el` IS the x-data element.
    root: null,

    init() {
      this.root = this.$el;
    },

    indicator(key) {
      if (this.key !== key) return '⇅';
      return this.dir === 1 ? '▲' : '▼';
    },

    // Dims inactive indicators so the active column's ▲/▼ stands out --
    // the old inline script did this by toggling has-text-grey-light via
    // classList on click. Kept next to indicator() since both derive from
    // the same key/dir state.
    indicatorClass(key) {
      return this.key === key ? '' : 'has-text-grey-light';
    },

    sortBy(key, type) {
      this.dir = this.key === key ? -this.dir : 1;
      this.key = key;

      // Each sortable <th> carries data-sort-key; its position in the
      // header row is the cell index to read in every body row.
      const columns = Array.from(this.root.querySelectorAll('thead th'));
      const colIndex = columns.findIndex((th) => th.dataset.sortKey === key);
      if (colIndex === -1) return;

      const body = this.root.querySelector('tbody');
      const rows = Array.from(body.querySelectorAll('tr'));

      const valueOf = (row) => {
        const cell = row.children[colIndex];
        if (!cell) return '';
        return cell.dataset.sortValue !== undefined
          ? cell.dataset.sortValue
          : cell.textContent.trim();
      };

      rows.sort((a, b) => {
        const av = valueOf(a);
        const bv = valueOf(b);
        if (type === 'number') {
          return ((parseFloat(av) || 0) - (parseFloat(bv) || 0)) * this.dir;
        }
        return av.localeCompare(bv) * this.dir;
      });

      rows.forEach((row) => body.appendChild(row));
    }
  }));

  // The export dropdown on the character and class pages. Owns the same
  // `open` state the inline `x-data="{ open: false }"` used to hold, plus the
  // download itself.
  //
  // WHY THE DOWNLOAD CANNOT JUST BE AN <a href> -- do not "simplify" this
  // component back into attributes; both attribute-only shapes were measured
  // and both are worse:
  //
  //   * Left boosted (hx-boost="true" sits on <body>), the click becomes an
  //     htmx AJAX GET. That request DOES carry the auth header, so the server
  //     returns the real file -- and then htmx ignores Content-Disposition:
  //     attachment and swaps the raw markdown/JSON into <body>. Nothing
  //     downloads; the page is destroyed instead. That is how this feature
  //     shipped, and it has never worked.
  //   * hx-boost="false", with or without a `download` attribute, makes it a
  //     real navigation. This app authenticates with an
  //     `Authorization: Bearer` header that JavaScript writes from
  //     localStorage (public/js/app.js's htmx:configRequest hook, ~:730) --
  //     the browser never sends it on a navigation. So the request bounces
  //     through /auth/check and what lands on disk is the ~6.6KB SIGN-IN
  //     PAGE, saved as the user's export. A download fires, so it looks
  //     fixed; it is not.
  //
  // The only shape that works is to make the request ourselves with the
  // header, then hand the browser a Blob it is willing to save.
  // `hx-boost="false"` on the anchors keeps htmx out of it, `@click.prevent`
  // keeps the browser's own navigation out of it, and a synthetic
  // `<a download>` over an object URL does the save.
  Alpine.data('exportDropdown', () => ({
    open: false,
    error: '',
    busy: false,

    // The server already names the file (routes/characters.js:801,
    // routes/classes.js:379); read that name back rather than reinventing it.
    // The RFC 5987 `filename*` form is preferred over plain `filename=`
    // because the latter has non-ASCII stripped out of it on the class route.
    filenameFrom(disposition, url) {
      const encoded = /filename\*=UTF-8''([^;]+)/i.exec(disposition || '');
      if (encoded) {
        try {
          return decodeURIComponent(encoded[1]);
        } catch (e) {
          // Malformed percent-encoding: fall through to the plain form.
        }
      }
      const plain = /filename="([^"]+)"/i.exec(disposition || '');
      if (plain) return plain[1];
      const format = new URL(url, window.location.origin).searchParams.get('format');
      return 'export.' + (format === 'markdown' ? 'md' : 'json');
    },

    download(url) {
      // Double-clicking a menu item must not start two downloads.
      if (this.busy) return Promise.resolve();
      this.busy = true;
      this.error = '';

      let objectUrl = null;
      return fetch(url, { headers: CharacterCommon.getAuthHeader() }).then((response) => {
        if (!response.ok) throw new Error('HTTP ' + response.status);
        // `ok` is NOT enough, and this check is the whole difference between a
        // working export and the bug this component exists to kill. An expired
        // or missing token does not produce a 401: util/auth.js redirects to
        // /auth/check, fetch follows that redirect transparently, and the
        // response is a perfectly `ok` 200 carrying ~6.6KB of sign-in page.
        // Saving that as the user's export is the exact false-green the
        // hx-boost="false" download shortcut produces. Every export route sets
        // Content-Disposition: attachment (routes/characters.js:800,
        // routes/classes.js:379); the sign-in page never does.
        const disposition = response.headers.get('Content-Disposition') || '';
        if (!/attachment/i.test(disposition)) {
          throw new Error('the server did not return a file (your session may have expired -- try reloading)');
        }
        return response.blob().then((blob) => {
          objectUrl = URL.createObjectURL(blob);
          const link = document.createElement('a');
          link.href = objectUrl;
          link.download = this.filenameFrom(response.headers.get('Content-Disposition'), url);
          // Must be in the document for the synthetic click to count as a
          // user-initiated download in every browser.
          document.body.appendChild(link);
          link.click();
          link.remove();
          this.open = false;
        });
      }).catch((err) => {
        // A failed export must not look like a successful one: the menu stays
        // open with the reason in it rather than closing on nothing at all.
        this.error = 'Export failed: ' + ((err && err.message) || 'Unknown error');
      }).finally(() => {
        // Revoked on a delay, not synchronously after click(): the browser
        // reads the blob out of the object URL asynchronously, and revoking
        // straight away can cancel the download it just started. Nothing else
        // holds a reference, so this is what keeps it from leaking.
        if (objectUrl) setTimeout(() => URL.revokeObjectURL(objectUrl), 1000);
        this.busy = false;
      });
    }
  }));
});
